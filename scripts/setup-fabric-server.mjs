#!/usr/bin/env node
/**
 * Set up a Fabric 26.3 server for the speedrun companion.
 *
 * Downloads the Fabric server launcher for 26.3, Fabric API and Carpet into a
 * target folder, drops the companion mod there, and writes a server.properties
 * with RCON enabled (the DSH plugin drives the bot through RCON).
 *
 * Your existing world is NOT touched: copy the `world/` folder from your current
 * server into the target folder yourself, so nothing is lost.
 *
 * Usage:
 *   node scripts/setup-fabric-server.mjs <targetDir> [--port 20000] [--rcon-port 25575] [--rcon-password secret]
 */
import { createWriteStream } from 'node:fs'
import { mkdir, readFile, writeFile, access } from 'node:fs/promises'
import { pipeline } from 'node:stream/promises'
import path from 'node:path'

const MC = '26.3'
const LOADER = '0.19.5'
const FABRIC_API = '0.161.0+26.3'
const CARPET = '26.3'

const args = process.argv.slice(2)
const targetDir = path.resolve(args[0] ?? 'fabric-26.3-server')
const option = (name, fallback) => {
  const index = args.indexOf(`--${name}`)
  return index >= 0 && args[index + 1] ? args[index + 1] : fallback
}
const port = option('port', '20000')
const rconPort = option('rcon-port', '25575')
const rconPassword = option('rcon-password', 'dsh-speedrun')

const log = (...values) => console.log('[setup]', ...values)

async function exists (file) {
  return access(file).then(() => true).catch(() => false)
}

async function download (url, file) {
  if (await exists(file)) {
    log(`skip (exists): ${path.basename(file)}`)
    return file
  }
  log(`download ${url}`)
  const response = await fetch(url)
  if (!response.ok) throw new Error(`GET ${url} -> ${response.status}`)
  await pipeline(response.body, createWriteStream(file))
  return file
}

/** Ask Fabric meta for the newest installer and launcher metadata. */
async function fabricMeta () {
  const res = await fetch(`https://meta.fabricmc.net/v2/versions/loader/${MC}/${LOADER}/server/json`)
  if (!res.ok) throw new Error(`fabric meta -> ${res.status}`)
  const data = await res.json()
  return data.launcherMeta
}

async function findCarpetUrl () {
  const res = await fetch('https://api.github.com/repos/gnembon/fabric-carpet/releases?per_page=10', {
    headers: { 'user-agent': 'dsh-mc', accept: 'application/vnd.github+json' }
  })
  if (!res.ok) throw new Error(`carpet releases -> ${res.status}`)
  const releases = await res.json()
  const match = releases.find((release) => release.tag_name === `v${CARPET}`)
  const asset = match?.assets?.find((entry) => entry.name.endsWith('.jar') && entry.name.includes(CARPET))
  if (!asset) throw new Error(`no Carpet ${CARPET} jar in the latest releases`)
  return { name: asset.name, url: asset.browser_download_url }
}

async function main () {
  await mkdir(path.join(targetDir, 'mods'), { recursive: true })

  const meta = await fabricMeta()
  const loaderEntry = meta.libraries.find((library) => library.name.includes('intermediary'))
  const launcherName = `fabric-server-mc.${MC}-loader.${LOADER}-launcher.${meta.libraries.length ? '1.0.1' : '1.0.1'}.jar`
  const serverJar = path.join(targetDir, 'fabric-server-launch.jar')
  const serverUrl = `https://meta.fabricmc.net/v2/versions/loader/${MC}/${LOADER}/server/jar`
  await download(serverUrl, serverJar)
  log(`server launcher: ${path.basename(serverJar)}${loaderEntry ? '' : ''}`)

  // Fabric API from the Fabric maven.
  const apiUrl = `https://maven.fabricmc.net/net/fabricmc/fabric-api/fabric-api/${encodeURIComponent(FABRIC_API)}/fabric-api-${encodeURIComponent(FABRIC_API)}.jar`
  await download(apiUrl, path.join(targetDir, 'mods', `fabric-api-${FABRIC_API}.jar`))

  // Carpet: the fake-player provider.
  const carpet = await findCarpetUrl()
  await download(carpet.url, path.join(targetDir, 'mods', carpet.name))

  // Our companion mod.
  const built = path.resolve(import.meta.dirname, '..', 'build', 'libs')
  const jar = (await readFile(path.join(built, '..', 'libs', 'dsh-mc-companion-server-0.1.0.jar')).catch(() => null))
    ? path.join(built, 'dsh-mc-companion-server-0.1.0.jar')
    : null
  if (!jar || !(await exists(jar))) {
    log('WARN: build/libs/dsh-mc-companion-server-0.1.0.jar missing — run "gradlew build" first, then copy it into mods/')
  } else {
    await writeFile(path.join(targetDir, 'mods', path.basename(jar)), await readFile(jar))
    log(`modded: ${path.basename(jar)}`)
  }

  const eula = path.join(targetDir, 'eula.txt')
  if (!(await exists(eula))) {
    await writeFile(eula, '# accepted by the speedrun companion setup\n')
    log('wrote eula.txt (edit eula=true to accept)')
  }

  const properties = [
    '# generated by setup-fabric-server.mjs',
    `server-port=${port}`,
    'online-mode=false',
    'enable-rcon=true',
    `rcon.port=${rconPort}`,
    `rcon.password=${rconPassword}`,
    'gamemode=survival',
    'spawn-protection=0',
    'allow-cheats=true',
    'level-name=world',
    ''
  ].join('\n')
  await writeFile(path.join(targetDir, 'server.properties'), properties)
  log(`server.properties: port ${port}, rcon ${rconPort}, password ${rconPassword}`)

  log('')
  log('next steps:')
  log('  1) copy your world:  <this folder>/world  <-  your current server world folder')
  log('  2) edit eula.txt:    eula=true')
  log(`  3) start:            java -Xmx4G -jar fabric-server-launch.jar nogui`)
  log('  4) in DSH:           set companion config transport="server", host=127.0.0.1, port=' + rconPort)
  log('  the bot itself is spawned by Carpet: /player Bot spawn')
}

main().catch((error) => {
  console.error('[setup] failed:', error.message)
  process.exit(1)
})
